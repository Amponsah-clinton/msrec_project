-- ---------------------------------------------------------------------
-- users_groups / users_user_permissions
-- Django's PermissionsMixin many-to-many join tables. auth.Group and
-- auth.Permission are Django's OWN built-in tables (auth_group,
-- auth_permission) — created later by the 'auth' app's migrations, not
-- by this file. Not used by any view in this project today; present
-- only because AbstractBaseUser + PermissionsMixin always defines them,
-- and Django's admin site (at /admin/, separate from this project's
-- /admins/) reads them.
--
-- Deliberately no `references public.auth_group/auth_permission` here:
-- this file runs before Django's own `auth` app has created those
-- tables (that's what "relation public.auth_group does not exist"
-- means if you hit it — auth_group/auth_permission are Django's to
-- create, on its first `python manage.py migrate`, not this file's).
-- group_id/permission_id are left as plain integers; Django manages the
-- real relationship in code and never actually re-runs this table's
-- DDL once `--fake-initial` marks it applied, so no constraint is lost
-- versus the recommended (migrate-only) path.
-- ---------------------------------------------------------------------
create table if not exists public.users_groups (
    id       bigint generated by default as identity primary key,
    user_id  bigint not null references public.users (id) on delete cascade,
    group_id integer not null,
    unique (user_id, group_id)
);

create table if not exists public.users_user_permissions (
    id            bigint generated by default as identity primary key,
    user_id       bigint not null references public.users (id) on delete cascade,
    permission_id integer not null,
    unique (user_id, permission_id)
);


