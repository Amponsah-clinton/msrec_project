-- ---------------------------------------------------------------------
-- payments
-- Mirrors payments.models.Payment. One row per Paystack transaction
-- attempt for an application's review fee (payments/fees.py) -- created
-- PENDING the moment an applicant is sent to checkout, *before* Paystack
-- is ever contacted, so there's always a row to reconcile a Paystack
-- callback/verify against. Only ever flipped to 'success' by
-- payments.services.verify_and_finalize() after Paystack's own
-- /transaction/verify/:reference confirms the real amount and currency
-- charged match -- never by anything the browser alone reports. An
-- application only becomes SUBMITTED (applicant_dashboard.views.
-- finalize_submission) once its payment is 'success', for any review
-- type the fee schedule doesn't mark fee-exempt. Read by both
-- secretariat_dashboard's and admin_dashboard's Finance pages.
-- ---------------------------------------------------------------------
create table if not exists public.payments (
    id                 bigint generated by default as identity primary key,
    application_id     bigint references public.applications (id) on delete cascade,
    applicant_id       bigint not null references public.users (id) on delete cascade,

    -- The Django model requires this with no default (payments.models.
    -- Payment.purpose) -- the default '' here only matters if you insert
    -- into this table directly, outside the ORM.
    purpose            varchar(150) not null default '',
    review_type        varchar(40) not null default '',

    -- Our own reference, generated before Paystack is ever contacted --
    -- not Paystack's, so a row to reconcile against always exists even if
    -- Paystack is never reached.
    reference          varchar(100) not null unique,

    amount             numeric(10, 2) not null default 0,
    currency           varchar(8) not null default 'GHS',

    status             varchar(10) not null default 'pending'
                       check (status in ('pending', 'success', 'failed')),

    -- Full verify-transaction payload from Paystack, kept for audit/dispute
    -- purposes (channel, card bin, gateway response, fees charged, ...).
    paystack_response  jsonb not null default '{}'::jsonb,

    created_at         timestamptz not null default now(),
    paid_at            timestamptz
);

comment on table public.payments is 'MSREC application review-fee payments via Paystack. payments.models.Payment maps onto this table 1:1.';
comment on column public.payments.status is 'pending | success | failed -- only payments.services.verify_and_finalize() (server-side Paystack verify) may set success.';

create index if not exists payments_applicant_id_idx on public.payments (applicant_id);
create index if not exists payments_application_id_idx on public.payments (application_id);
create index if not exists payments_status_idx on public.payments (status);

alter table public.payments enable row level security;

drop policy if exists "service_role full access to payments" on public.payments;
create policy "service_role full access to payments"
    on public.payments for all
    to service_role
    using (true) with check (true);

