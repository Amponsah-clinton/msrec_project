-- ---------------------------------------------------------------------
-- password_reset_codes
-- Mirrors accounts.models.PasswordResetCode. One row per 6-digit code
-- issued by the Forgot Password flow (pages:forgot_password /
-- pages:reset_password, accounts/views.py) -- never reused or edited in
-- place, so this doubles as an audit trail of every reset attempt
-- against an account, the same "one row per attempt" idea as
-- role_approval_logs above. A code is spent (used_at set) the moment a
-- reset succeeds; every other still-open code for that user is spent in
-- the same update, so an old code from an earlier request can never
-- outlive a successful reset.
-- ---------------------------------------------------------------------
create table if not exists public.password_reset_codes (
    id          bigint generated by default as identity primary key,
    user_id     bigint not null references public.users (id) on delete cascade,

    code        varchar(6) not null,
    created_at  timestamptz not null default now(),
    expires_at  timestamptz not null,
    used_at     timestamptz
);

comment on table public.password_reset_codes is 'Forgot Password 6-digit codes, one row per code issued. accounts.models.PasswordResetCode maps onto this table 1:1.';
comment on column public.password_reset_codes.used_at is 'Set the moment a reset succeeds (or the code is superseded by a later reset) -- null means still open and unused.';

create index if not exists password_reset_codes_user_id_idx on public.password_reset_codes (user_id);
create index if not exists password_reset_codes_user_open_idx on public.password_reset_codes (user_id, created_at desc) where used_at is null;

alter table public.password_reset_codes enable row level security;

drop policy if exists "service_role full access to password_reset_codes" on public.password_reset_codes;
