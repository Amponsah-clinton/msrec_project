-- ==========================================================================
-- MSREC — Supabase / Postgres schema for accounts (signup, login, roles)
-- ==========================================================================
--
-- WHAT THIS IS
-- Django owns this schema via accounts/migrations/0001_initial.py. The
-- columns, types and constraints below are a byte-for-byte translation of
-- that migration into hand-written SQL, for two reasons:
--   1. You asked for something you can paste into the Supabase SQL editor
--      and inspect/run directly.
--   2. It gives you RLS policies, which a Django migration never writes.
--
-- WHICH PATH TO ACTUALLY USE
--   Recommended (simplest, and what was tested end-to-end for this build):
--     1. Create a Supabase project, copy its Postgres connection string.
--     2. Put it in .env as DATABASE_URL=postgresql://... (see .env.example).
--     3. Run: python manage.py migrate
--     Django creates every table below itself. You never need this file.
--
--   Alternative (if you'd rather provision the tables from the Supabase
--   SQL editor first, e.g. to review/tweak them before Django touches
--   anything):
--     1. Run this whole file in the Supabase SQL editor.
--     2. Run: python manage.py migrate --fake-initial
--        (tells Django "these tables already exist with this shape, just
--        record the migration as applied" instead of trying to CREATE them
--        again).
--
-- Either path lands on the identical schema, so accounts/models.py (the
-- Django User model) works unmodified against it either way.
--
-- WHY RLS BARELY MATTERS HERE, BUT IS ENABLED ANYWAY
-- The Django app authenticates with Django's own session-based login
-- (accounts/views.py) and talks to Postgres directly over DATABASE_URL,
-- using the Postgres role from your Supabase connection string — normally
-- a privileged role that bypasses RLS entirely. Nothing in this project
-- calls Supabase's PostgREST/GoTrue API with the anon or authenticated
-- JWT, so these policies are not what protects this app's users right now
-- (Django's own auth does that). RLS is turned on anyway, with a
-- deny-by-default posture, as a safety net for the day something else
-- (Supabase's auto-generated REST API, a future serverless function,
-- someone poking at the anon key) tries to query these tables directly.
-- ==========================================================================


-- ---------------------------------------------------------------------
-- users
-- Mirrors accounts.models.User. One row per MSREC account. Every signup
-- lands here with role='applicant' (no approval needed — applying is the
-- default capability). wants_reviewer/wants_committee + their *_status
-- columns track the two roles that DO need an admin's sign-off; see
-- reviewer_status/committee_status below and role_approval_logs for the
-- audit trail admin_dashboard's Accounts page writes to.
-- ---------------------------------------------------------------------
create table if not exists public.users (
    id                      bigint generated by default as identity primary key,

    -- Auth (Django's AbstractBaseUser + PermissionsMixin contract)
    password                varchar(128) not null,
    last_login              timestamptz,
    is_superuser            boolean not null default false,
    is_staff                boolean not null default false,
    is_active               boolean not null default true,

    -- Identity
    email                   varchar(254) not null unique,
    date_joined             timestamptz not null default now(),

    -- Personal info (from the signup form's Personal Information section)
    first_name              varchar(150) not null,
    middle_name             varchar(150) not null default '',
    last_name               varchar(150) not null,
    title                   varchar(20)  not null default '',
    phone                   varchar(40)  not null default '',
    country_residence       varchar(120) not null default '',
    highest_qualification   varchar(150) not null default '',

    -- Institution / Professional Information section
    institution             varchar(200) not null default '',
    department              varchar(200) not null default '',
    position                varchar(150) not null default '',
    institution_country     varchar(120) not null default '',
    institution_address     varchar(255) not null default '',
    profile_url             varchar(200) not null default '',
    no_institution           boolean not null default false,
    -- Object path inside the private "signup" Supabase Storage bucket
    -- (accounts/storage.py) -- not a public URL; resolve with a signed URL.
    profile_photo_path      varchar(500) not null default '',

    -- Primary role: which dashboard this account lands on after login
    -- (see User.dashboard_url_name() in accounts/models.py).
    role                    varchar(20) not null default 'applicant'
                            check (role in ('applicant', 'reviewer', 'committee', 'chair', 'secretariat', 'admin')),

    -- Reviewer role request + its extra signup-form answers
    wants_reviewer          boolean not null default false,
    reviewer_status         varchar(20) not null default 'not_requested'
                            check (reviewer_status in ('not_requested', 'pending', 'approved', 'rejected')),
    reviewer_profile        jsonb not null default '{}'::jsonb,

    -- Committee role request + its extra signup-form answers
    wants_committee         boolean not null default false,
    committee_status        varchar(20) not null default 'not_requested'
                            check (committee_status in ('not_requested', 'pending', 'approved', 'rejected')),
    committee_profile       jsonb not null default '{}'::jsonb,

    -- Applicant-specific signup-form answers (always collected; applicant
    -- access itself never needs approval)
    applicant_profile       jsonb not null default '{}'::jsonb
);

comment on table public.users is 'MSREC accounts. Django''s AUTH_USER_MODEL (accounts.User) maps onto this table 1:1.';
comment on column public.users.role is 'Primary/active role — decides which dashboard a login lands on.';
comment on column public.users.reviewer_status is 'not_requested | pending | approved | rejected — set to pending at signup when wants_reviewer is checked, flipped by an admin in Accounts > Pending Approval.';
comment on column public.users.committee_status is 'Same lifecycle as reviewer_status, for the Committee Member role.';

-- Case-insensitive login lookups and the accounts-page tab counts both
-- filter on these constantly.
create index if not exists users_email_lower_idx on public.users (lower(email));
create index if not exists users_role_idx on public.users (role);
create index if not exists users_reviewer_status_idx on public.users (reviewer_status) where reviewer_status = 'pending';
create index if not exists users_committee_status_idx on public.users (committee_status) where committee_status = 'pending';


-- ---------------------------------------------------------------------
-- role_approval_logs
-- Audit trail for every admin approve/reject decision on a reviewer or
-- committee request (accounts.models.RoleApprovalLog). Written by
-- admin_dashboard.views.accounts() each time an admin acts on a request.
-- ---------------------------------------------------------------------
create table if not exists public.role_approval_logs (
    id          bigint generated by default as identity primary key,
    user_id     bigint not null references public.users (id) on delete cascade,
    role        varchar(20) not null
                check (role in ('applicant', 'reviewer', 'committee', 'chair', 'secretariat', 'admin')),
    action      varchar(20) not null check (action in ('approved', 'rejected')),
    acted_by_id bigint references public.users (id) on delete set null,
    note        varchar(255) not null default '',
    created_at  timestamptz not null default now()
);

comment on table public.role_approval_logs is 'Audit trail: who approved/rejected which reviewer or committee request, and when.';

create index if not exists role_approval_logs_user_id_idx on public.role_approval_logs (user_id);
create index if not exists role_approval_logs_created_at_idx on public.role_approval_logs (created_at desc);


-- ---------------------------------------------------------------------
-- users_groups / users_user_permissions
-- Django's PermissionsMixin many-to-many join tables. auth.Group and
-- auth.Permission are Django's OWN built-in tables (auth_group,
-- auth_permission) — created later by the 'auth' app's migrations, not
-- by this file. Not used by any view in this project today; present
-- only because AbstractBaseUser + PermissionsMixin always defines them,
-- and Django's admin site (at /admin/, separate from this project's
-- /admins/) reads them.
--
-- Deliberately no `references public.auth_group/auth_permission` here:
-- this file runs before Django's own `auth` app has created those
-- tables (that's what "relation public.auth_group does not exist"
-- means if you hit it — auth_group/auth_permission are Django's to
-- create, on its first `python manage.py migrate`, not this file's).
-- group_id/permission_id are left as plain integers; Django manages the
-- real relationship in code and never actually re-runs this table's
-- DDL once `--fake-initial` marks it applied, so no constraint is lost
-- versus the recommended (migrate-only) path.
-- ---------------------------------------------------------------------
create table if not exists public.users_groups (
    id       bigint generated by default as identity primary key,
    user_id  bigint not null references public.users (id) on delete cascade,
    group_id integer not null,
    unique (user_id, group_id)
);

create table if not exists public.users_user_permissions (
    id            bigint generated by default as identity primary key,
    user_id       bigint not null references public.users (id) on delete cascade,
    permission_id integer not null,
    unique (user_id, permission_id)
);


-- ==========================================================================
-- Row Level Security — deny-by-default; only a privileged role (Django's
-- DATABASE_URL connection, or Supabase's service_role) can read/write.
-- ==========================================================================
alter table public.users                  enable row level security;
alter table public.role_approval_logs     enable row level security;
alter table public.users_groups           enable row level security;
alter table public.users_user_permissions enable row level security;

-- drop-then-create (rather than "if not exists", which create policy has
-- no syntax for) so this whole file can be re-run safely, e.g. after
-- fixing a typo or re-running following an earlier error partway through.
drop policy if exists "service_role full access to users" on public.users;
create policy "service_role full access to users"
    on public.users for all
    to service_role
    using (true) with check (true);

drop policy if exists "service_role full access to role_approval_logs" on public.role_approval_logs;
create policy "service_role full access to role_approval_logs"
    on public.role_approval_logs for all
    to service_role
    using (true) with check (true);

drop policy if exists "service_role full access to users_groups" on public.users_groups;
create policy "service_role full access to users_groups"
    on public.users_groups for all
    to service_role
    using (true) with check (true);

drop policy if exists "service_role full access to users_user_permissions" on public.users_user_permissions;
create policy "service_role full access to users_user_permissions"
    on public.users_user_permissions for all
    to service_role
    using (true) with check (true);

