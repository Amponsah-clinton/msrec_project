-- ---------------------------------------------------------------------
-- applications
-- Mirrors applicant_dashboard.models.Application. One row per Universal
-- Research Ethics Application submission (templates/dashboards/applicant/
-- application-form.html). The form has ~90 fields across 15 sections that
-- vary a lot by study type, so every posted field lands in `form_data`
-- (jsonb) keyed by its form `name`, keeping only the handful of columns
-- other views/queries actually need as real columns. Uploaded documents
-- go to the "application" Supabase Storage bucket (applicant_dashboard/
-- storage.py) and are recorded in `documents` as
-- [{"name", "path", "size", "content_type"}, ...].
-- ---------------------------------------------------------------------
create table if not exists public.applications (
    id             bigint generated by default as identity primary key,
    applicant_id   bigint not null references public.users (id) on delete cascade,

    -- Assigned once, right after the row first gets its id -- see
    -- Application.assign_reference_no(). NULL (not '') until then: a
    -- unique constraint treats every '' as equal, so a second draft (or
    -- any pre-assignment row) would collide on save; NULL is exempt from
    -- a unique constraint (Postgres allows any number of them).
    reference_no   varchar(40) unique,

    review_type    varchar(40) not null default '',
    status         varchar(20) not null default 'draft'
                   check (status in ('draft', 'submitted', 'under_review', 'revisions_required', 'approved', 'not_approved')),

    form_data      jsonb not null default '{}'::jsonb,
    documents      jsonb not null default '[]'::jsonb,

    -- Client-computed "answered / visible fields" heuristic from apply.js's
    -- updateProgress(), sent with every autosave -- lets the Drafts list
    -- show/sort completion without re-parsing form_data. Meaningless once
    -- status != 'draft' (submit forces it to 100).
    completion_pct smallint not null default 0,

    submitted_at   timestamptz,
    -- Set once, when the Secretariat moves this application to approved or
    -- not_approved (secretariat_dashboard.views) -- the real decision date
    -- shown on Approved Studies / Not Approved (not updated_at, which also
    -- moves on every other status change).
    decided_at     timestamptz,

    -- Revisions round-trip -- set by applicant_dashboard.oversight.apply_transition()
    -- when the Secretariat requests revisions (revision_comment is their
    -- optional note on what to fix), and by application_form when the
    -- applicant fixes and resends. resubmitted_at is the "revision was
    -- done on this application" indicator shown across every applications
    -- list/detail page; revision_count keeps incrementing across rounds
    -- and is never reset, even once the application is later decided.
    revision_comment       text not null default '',
    revision_requested_at  timestamptz,
    revision_count         smallint not null default 0,
    resubmitted_at         timestamptz,

    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now()
);

comment on table public.applications is 'MSREC ethics application submissions. applicant_dashboard.models.Application maps onto this table 1:1.';
comment on column public.applications.form_data is 'Every named field from the application form, as posted -- see applicant_dashboard.views._collect_form_data.';
comment on column public.applications.documents is 'Uploaded documents: object paths inside the "application" Storage bucket, plus display metadata.';
comment on column public.applications.resubmitted_at is 'Set only when the applicant actually fixes and resends after a revision request -- NULL means never resubmitted. This is the "revision was done" indicator.';

create index if not exists applications_applicant_id_idx on public.applications (applicant_id);
create index if not exists applications_status_idx on public.applications (status);

