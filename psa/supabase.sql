-- =====================================================================
-- Professional Service Agreements (PSA) -- table for Supabase Postgres.
--
-- Same tables Django's migrations psa/0001 - 0003 create. Run it in
-- Supabase -> SQL Editor, then deploy the code. The last statement records
-- the migrations as applied, so `python manage.py migrate` skips them
-- instead of trying to create the tables a second time.
--
-- Safe to run more than once, and safe to run over the earlier version of
-- this file: every statement checks first, and the upgrade section below
-- brings an existing table up to date.
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.service_agreements (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- identity
    reference                varchar(30),                        -- PSA-2026-0001, numbered right after insert
    token                    varchar(64)  NOT NULL,              -- secret key in the client's link
    status                   varchar(12)  NOT NULL DEFAULT 'draft',

    -- 1. the parties
    agreement_date           date         NOT NULL DEFAULT CURRENT_DATE,
    provider_name            varchar(120) NOT NULL DEFAULT 'METASCHOLAR LIMITED',
    provider_address         varchar(255) NOT NULL DEFAULT 'P.O. Box SY649 Fiapre–Sunyani, Bono Region Ghana.',
    client_name              varchar(200) NOT NULL,
    client_email             varchar(254) NOT NULL DEFAULT '',
    client_phone             varchar(40)  NOT NULL DEFAULT '',
    client_address           varchar(255) NOT NULL DEFAULT '',

    -- 2. term
    start_date               date,
    completion_date          date,

    -- 3. the service
    service_title            varchar(255) NOT NULL DEFAULT '',
    deliverables             jsonb        NOT NULL DEFAULT '[]'::jsonb,

    -- 4. payment
    currency                 varchar(3)   NOT NULL DEFAULT 'GHS',
    fee                      numeric(14, 2),
    payment_basis            varchar(12)  NOT NULL DEFAULT ''
                             CHECK (payment_basis IN ('', 'fixed', 'hourly', 'milestone', 'other')),
    payment_basis_other      varchar(120) NOT NULL DEFAULT '',
    deposit                  numeric(14, 2) NOT NULL DEFAULT 0,
    payment_schedule         text         NOT NULL DEFAULT '',

    -- for Metascholar Limited
    company_signatory_name   varchar(200) NOT NULL DEFAULT '',
    company_signatory_role   varchar(60)  NOT NULL DEFAULT '',
    company_signature_kind   varchar(6)   NOT NULL DEFAULT ''
                             CHECK (company_signature_kind IN ('', 'drawn', 'typed')),
    company_signature        text         NOT NULL DEFAULT '',   -- PNG data: URL, or the typed name
    company_signed_at        timestamptz,
    company_signed_by_id     bigint REFERENCES public.users (id)
                             ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,

    -- 5. client review and acceptance
    client_signature_kind    varchar(6)   NOT NULL DEFAULT ''
                             CHECK (client_signature_kind IN ('', 'drawn', 'typed')),
    client_signature         text         NOT NULL DEFAULT '',
    client_signed_at         timestamptz,
    client_signed_ip         inet,
    client_user_agent        varchar(300) NOT NULL DEFAULT '',

    -- tracking
    created_by_id            bigint REFERENCES public.users (id)
                             ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    created_at               timestamptz  NOT NULL DEFAULT now(),
    updated_at               timestamptz  NOT NULL DEFAULT now(),
    sent_at                  timestamptz,
    last_sent_at             timestamptz,
    send_count               integer      NOT NULL DEFAULT 0 CHECK (send_count >= 0),
    viewed_at                timestamptz,
    cancelled_at             timestamptz,

    CONSTRAINT service_agreements_reference_key UNIQUE (reference),
    CONSTRAINT service_agreements_token_key     UNIQUE (token),
    CONSTRAINT service_agreements_deposit_check CHECK (deposit >= 0),
    CONSTRAINT service_agreements_fee_check     CHECK (fee IS NULL OR fee >= 0)
);

-- Allowed statuses. Dropped and re-added so a table made by the earlier
-- version of this file (which didn't know 'changes') is upgraded too.
ALTER TABLE public.service_agreements DROP CONSTRAINT IF EXISTS service_agreements_status_check;
ALTER TABLE public.service_agreements ADD CONSTRAINT service_agreements_status_check
    CHECK (status IN ('draft', 'sent', 'changes', 'signed', 'cancelled'));

-- What the PSA list filters and sorts on.
CREATE INDEX IF NOT EXISTS service_agreements_status_idx         ON public.service_agreements (status);
CREATE INDEX IF NOT EXISTS service_agreements_created_at_idx     ON public.service_agreements (created_at DESC);
CREATE INDEX IF NOT EXISTS service_agreements_agreement_date_idx ON public.service_agreements (agreement_date);
CREATE INDEX IF NOT EXISTS service_agreements_created_by_idx     ON public.service_agreements (created_by_id);
CREATE INDEX IF NOT EXISTS service_agreements_company_signed_by_idx ON public.service_agreements (company_signed_by_id);

-- Agreements hold client contact details, signatures and the secret link
-- token. With RLS on and no policies, Supabase's public REST API (anon and
-- authenticated keys) can't read or write this table at all; the Django
-- app connects as the table owner, which isn't affected.
ALTER TABLE public.service_agreements ENABLE ROW LEVEL SECURITY;

-- The client flagging something to fix instead of signing, and how
-- Metascholar answered (one row per round).
CREATE TABLE IF NOT EXISTS public.service_agreement_change_requests (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id    bigint NOT NULL REFERENCES public.service_agreements (id)
                    ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    section         varchar(12) NOT NULL DEFAULT 'other'
                    CHECK (section IN ('parties', 'term', 'service', 'payment', 'other')),
    message         text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    client_ip       inet,
    resolved_at     timestamptz,
    resolved_by_id  bigint REFERENCES public.users (id)
                    ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    response        text        NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS service_agreement_change_requests_agreement_idx
    ON public.service_agreement_change_requests (agreement_id, created_at DESC);
CREATE INDEX IF NOT EXISTS service_agreement_change_requests_resolved_by_idx
    ON public.service_agreement_change_requests (resolved_by_id);

-- Holds what clients wrote; same protection as the agreements.
ALTER TABLE public.service_agreement_change_requests ENABLE ROW LEVEL SECURITY;

-- Money received against an agreement (the ledger behind "amount owing").
-- Write-once: the app never updates or deletes a row -- a mistake is
-- corrected by a further row, negative for a refund (see psa/models.py).
CREATE TABLE IF NOT EXISTS public.service_agreement_payments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id    bigint NOT NULL REFERENCES public.service_agreements (id)
                    ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    amount          numeric(14, 2) NOT NULL,
    paid_on         date        NOT NULL DEFAULT CURRENT_DATE,
    method          varchar(10) NOT NULL DEFAULT 'bank'
                    CHECK (method IN ('cash', 'bank', 'momo', 'cheque', 'card', 'other')),
    note            varchar(200) NOT NULL DEFAULT '',
    recorded_by_id  bigint REFERENCES public.users (id)
                    ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    recorded_at     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT service_agreement_payments_amount_nonzero CHECK (amount <> 0)
);

CREATE INDEX IF NOT EXISTS service_agr_payments_idx
    ON public.service_agreement_payments (agreement_id, paid_on DESC);
CREATE INDEX IF NOT EXISTS service_agreement_payments_recorded_by_idx
    ON public.service_agreement_payments (recorded_by_id);

-- Amounts and who paid what: same protection as the agreements.
ALTER TABLE public.service_agreement_payments ENABLE ROW LEVEL SECURITY;

-- Tell Django the tables already exist (the PSA migrations below; 0004
-- only adds the letterhead settings table, which `migrate` creates).
INSERT INTO public.django_migrations (app, name, applied)
