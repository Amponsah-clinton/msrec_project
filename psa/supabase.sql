FROM (VALUES ('psa', '0001_initial'), ('psa', '0002_reference_null_until_numbered'),
             ('psa', '0003_client_change_requests'), ('psa', '0005_payment')) AS m (app, name)
WHERE NOT EXISTS (
    SELECT 1 FROM public.django_migrations d WHERE d.app = m.app AND d.name = m.name
);

COMMIT;
